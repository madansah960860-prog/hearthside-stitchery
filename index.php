        </div>
        <ul class="why-grid">
          <li>
            <h3>Fibre content and yardage on every page</h3>
            <p>Exact percentages, weight in grams, yardage per skein, band gauge and dye-lot policy.
               You should never have to email a yarn shop to find out what the yarn is made of.</p>
          </li>
          <li>
            <h3>Washing rules before you buy, not after</h3>
            <p>Superwash or not, hand wash or machine, flat dry or line. It is on the product page,
               because finding out after you have knitted a sweater is too late.</p>
          </li>
          <li>
            <h3>Skill labels that describe the work</h3>
            <p>Beginner, Confident or Experienced, and each one explained in the footer. They describe
               what a project asks of you. They are not ratings and they are not about you.</p>
          </li>
          <li>
            <h3>30 days, and the uncut rule stated plainly</h3>
            <p>$5.95 flat shipping, free over $45. 30 days to return anything unused. Yarn and fabric have
               to be uncut and still banded — we say that here, on every product page, and in the
               cart, not only in the small print.</p>
