          <div class="section-head">
            <h2 id="story-title">Why we write so much down</h2>
          </div>
          <p>Hearthside began as a Tuesday evening class in the back of a church hall on Millrace Road.
             The pattern of the whole eight weeks was always the same: somebody would arrive with yarn
             bought online, and nobody — including the person who bought it — could say what it was
             made of, whether it would survive a wash, or how much of it there was.</p>
          <p>That is the entire reason this shop exists and the reason every page here reads like a
             specification. Fibre content, weight, yardage, gauge, dye lot, and the washing rules. If
             we cannot get those facts out of a supplier, we do not stock the thing.</p>
          <p>We also write the awkward bits down. Not-superwash yarn will felt in a machine. A cutting
             mat stored upright warps and never recovers. A quilt kit is fabric and instructions, not a
             quilt. None of that is good marketing and all of it is true.</p>
          <p><a href="about.html">More about how we choose what to stock</a></p>
